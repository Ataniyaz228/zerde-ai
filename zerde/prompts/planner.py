from __future__ import annotations

# Подсказки «обиходное название → law_id/adilet-код» для планировщика.
# Это advisory-хинты для LLM (НЕ резолвер), но для законов, реально присутствующих
# в корпусе, значения ОБЯЗАНЫ совпадать с каноном реестра: иначе планировщик уводит
# ретривал в мёртвый ID (классика — налоговый=120-VI вместо 214-VII, после чего
# adilet-код не находится и грунтинг молча теряется). S2 всё равно прогоняет law_ids
# через registry.resolve(), а кодексы с тег-суффиксом (226-V→226-V-UK, 414-I→414-I-NEW)
# самолечатся base-ID матчингом. CI-гард: tests/test_planner_law_hints.py.
_PLANNER_LAW_CODE_HINTS: dict[str, str] = {
    "ГК РК (Общая часть)": "1000-XIII",
    "ГК РК (Особенная часть)": "409-I",
    "Земельный кодекс РК": "442-II",
    "Бюджетный кодекс РК": "171-VIII",  # 95-IV (2008) утратил силу → 171-VIII (2025)
    "КоАП РК": "235-V",
    "УК РК": "226-V",
    "Трудовой кодекс РК": "414-I",
    "Налоговый кодекс РК": "214-VII",  # было 120-VI (мёртвый ID) — стейл-баг грунтинга
    "О государственном имуществе": "413-IV",
    "О местном госуправлении": "148-II",
    "О персональных данных": "94-V",
    "Об образовании": "319-III",
    "О науке": "407-II",
    "О секьюритизации": "122-IV",
    "Об оценочной деятельности": "368-II",
    "Предпринимательский кодекс": "375-V",
}


def _render_law_code_hints() -> str:
    """Рендерит таблицу хинтов для промпта (источник — _PLANNER_LAW_CODE_HINTS)."""
    return "\n".join(f"- {name} = {code}" for name, code in _PLANNER_LAW_CODE_HINTS.items())


_PLANNER_SYSTEM_SCHEMA = """
Верни JSON строго следующей структуры:
{
  "adilet_queries": [
    {
      "query_text": "...",
      "law_ids": ["550-IV", ...],
      "articles": ["15", "15-1", ...],
      "date_from": "YYYY-MM-DD",  // optional
      "date_to": "YYYY-MM-DD"    // optional
    }
  ],
  "web_queries_ru": [
    {
      "query_text": "...",
      "include_domains": ["gov.kz", ...],  // optional
      "max_results": 5
    }
  ],
  "web_queries_kk": [...],
  "web_queries_en": [...],
  "expected_elements": ["список ожидаемых элементов анализа"],
  "bylaw_triggers": ["список потенциальных подзаконных актов"]
}
"""

_PLANNER_USER_TEMPLATE = """
Ты — юридический аналитик-планировщик для Республики Казахстан.
Проанализируй следующий документ и составь план поиска нормативно-правовой базы.

## Документ:
__DOCUMENT_TEXT__

## Задача:
1. Определи ВСЕ НПА (нормативно-правовые акты) РК, которые НЕОБХОДИМО проверить.
2. Составь конкретные запросы к базе данных Адилет (adilet.zan.kz).
3. Составь Web-запросы на русском, казахском и английском языках.
4. Укажи ожидаемые элементы анализа (expected_elements).
5. Укажи подзаконные акты, которые могут быть вовлечены (bylaw_triggers).

## ⚠️ КРИТИЧЕСКИЕ ТРЕБОВАНИЯ К ПЛАНУ:

### Извлечение ссылок на НПА из документа:
- Каждый номер закона (87-IV, 94-V, 235-V) → adilet_query с law_ids
- Статьи указывай ТОЛЬКО упомянутые в документе (НЕ перечисляй все статьи закона!)
- Группируй: один закон = один adilet_query (не дели на отдельные запросы по статьям)
- МАКСИМУМ 8 adilet_queries. Объединяй родственные законы.

### ❗ ФОРМАТ law_ids — КРИТИЧЕСКИ ВАЖНО:
law_ids ДОЛЖНЫ содержать ТОЛЬКО короткие ID вида "{number}-{roman}" или Adilet-код вида "K940001000_".
НИКОГДА не используй названия законов!
❌ Плохо: "law_ids": ["Гражданский кодекс РК"]  ← НЕВЕРНО!
❌ Плохо: "law_ids": ["Земельный кодекс РК"]  ← НЕВЕРНО!
❌ Плохо: "law_ids": ["Закон о государственном имуществе"]  ← НЕВЕРНО!
✅ Правильно: "law_ids": ["1000-XIII"]  ← ГК РК (Общая часть)
✅ Правильно: "law_ids": ["442-II"]  ← Земельный кодекс
✅ Правильно: "law_ids": ["413-IV"]  ← О государственном имуществе

Справочная таблица основных кодов:
- Конституция РК = K950001000_ (⚠️ ВНИМАНИЕ: никогда не используй ГК K940001000_ для Конституции!)
__LAW_CODE_HINTS__
Если код закона не известен — используй формат "Номер-Созыв", например "550-IV".

### 🇰🇿 КАЗАХСКИЙ КОНТЕКСТ И ЯЗЫК (Казахский язык):
- Если документ на казахском языке (или содержит казахские термины):
  - Казахские аббревиатуры кодексов: "ӘҚБтК" / "ӘҚБТК" (КоАП = 235-V), "ҚК" / "ҚҚ" (УК = 226-V), "АК" (ГК = 1000-XIII/309-II), "ЖК" (ЗК = 442-II).
  - Упоминание статей на казахском идет через дефис "-бап", "-бабы", "-бабының", "-бапта" (например: "61-бап", "889-1-бабы"). Обязательно извлекай эти статьи в `articles` для соответствующего кодекса!
  - Месячный расчетный показатель (МРП) на казахском языке называется "АЕК" (Айлық есептік көрсеткіш).
  - Для казахских документов составляй качественные, подробные `web_queries_kk` на казахском языке (например: "ӘҚБтК 61-бабы рақымшылық 2026").

### Проверка числовых утверждений:
- Если документ упоминает МРП (месячный расчётный показатель) — ОБЯЗАТЕЛЬНО добавь web_query:
  "МРП {год} размер тенге республиканский бюджет" (max_results: 3)
- Если документ упоминает штрафы в МРП — добавь adilet_query на соответствующую статью КоАП/УК
- Если документ указывает сроки (часы, дни) — добавь запрос на проверку этих сроков

### Конкретность запросов:
Web-запросы должны быть КОНКРЕТНЫМИ, не общими!
❌ Плохо: "защита персональных данных казахстан 2025"
✅ Хорошо: "Закон РК 94-V персональные данные статья 9 срок уведомления"
✅ Хорошо: "КоАП РК статья 79 штраф персональные данные 2025"
✅ Хорошо: "МРП 2025 размер месячный расчетный показатель закон"
✅ Хорошо: "ППРК номер 142 персональные данные"

### Ограничение количества:
- max_results для web_queries: НЕ БОЛЕЕ 5
- adilet_queries: МАКСИМУМ 8
- web_queries_ru: 5-8 запросов максимум
- web_queries_kk: 3-5 запросов максимум
- web_queries_en: 2-3 запроса максимум

### ❗ COMPACT JSON — КРИТИЧЕСКИ ВАЖНО:
- articles: ТОЛЬКО конкретно упомянутые в документе (не перечисляй все статьи закона!)
- query_text: короткие строки до 80 символов
- НЕ повторяй один закон в нескольких запросах
- Общий ответ должен вместиться в 4000 токенов!

## Контекст КЗ права:
- Источники по убыванию авторитета: Международные договоры > Кодексы > Конституционные законы > Законы РК > Указы Президента > Постановления Правительства > Приказы министерств
- Для Адилет: ID закона обычно вида "550-IV", статьи — "15", "15-1"
- Web Gov источники (TIER_1): gov.kz, adilet.zan.kz, supreme.kz, primeminister.kz
- УК РК = Закон 226-V (Уголовный кодекс)
- КоАП = Закон 235-V (Кодекс об административных правонарушениях)
- Закон о персональных данных = 94-V

__SCHEMA__
"""


def build_planner_prompt(document_text: str, max_chars: int = 12_000) -> str:
    """
    Строит промпт для LLM Planner.

    Args:
        document_text: Нормализованный текст документа.
        max_chars: Максимальное количество символов документа в промпте.

    Returns:
        Готовый промпт-строка.
    """
    # Обрезаем если слишком длинный документ
    if len(document_text) > max_chars:
        truncated = document_text[:max_chars]
        truncated += f"\n\n[... текст обрезан — оригинал содержит {len(document_text)} символов ...]"
    else:
        truncated = document_text

    # Используем простую замену вместо str.format() —
    # шаблон содержит {год} и {дата} буквально (не переменные),
    # а схема содержит JSON с {} → str.format() всегда даст KeyError.
    return (
        _PLANNER_USER_TEMPLATE
        .replace("__DOCUMENT_TEXT__", truncated)
        .replace("__LAW_CODE_HINTS__", _render_law_code_hints())
        .replace("__SCHEMA__", _PLANNER_SYSTEM_SCHEMA)
    )
