function p(text, opts = {}) {
  return new Paragraph({
    alignment: opts.align || AlignmentType.JUSTIFIED,
    spacing: { before: opts.before ?? 120, after: opts.after ?? 120, line: 276 },
    children: [new TextRun({
      text,
      bold: opts.bold || false,
      italic: opts.italic || false,
      size: opts.size || 24,
      font: "Times New Roman",
      color: opts.color || "000000",
    })]
  });
}

function h1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    alignment: AlignmentType.CENTER,
    spacing: { before: 360, after: 240 },
    children: [new TextRun({ text, bold: true, size: 28, font: "Times New Roman", allCaps: true })]
  });
}

function h2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    alignment: AlignmentType.LEFT,
    spacing: { before: 300, after: 180 },
    children: [new TextRun({ text, bold: true, size: 26, font: "Times New Roman" })]
  });
}

function h3(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_3,
    alignment: AlignmentType.LEFT,
    spacing: { before: 240, after: 120 },
    children: [new TextRun({ text, bold: true, italic: true, size: 24, font: "Times New Roman" })]
  });
}

function article(num, title, content) {
  const paragraphs = [];
  paragraphs.push(new Paragraph({
    alignment: AlignmentType.JUSTIFIED,
    spacing: { before: 240, after: 120 },
    children: [
      new TextRun({ text: `Статья ${num}. `, bold: true, size: 24, font: "Times New Roman" }),
      new TextRun({ text: title, bold: true, size: 24, font: "Times New Roman" }),
    ]
  }));
  content.forEach(txt => paragraphs.push(p(txt)));
  return paragraphs;
}

function bulletItem(text) {
  return new Paragraph({
    alignment: AlignmentType.JUSTIFIED,
    spacing: { before: 60, after: 60, line: 276 },
    numbering: { reference: "bullets", level: 0 },
    children: [new TextRun({ text, size: 24, font: "Times New Roman" })]
  });
}

function numbered(text, n) {
  return new Paragraph({
    alignment: AlignmentType.JUSTIFIED,
    spacing: { before: 60, after: 60, line: 276 },
    numbering: { reference: `num${n}`, level: 0 },
    children: [new TextRun({ text, size: 24, font: "Times New Roman" })]
  });
}

function emptyLine() {
  return new Paragraph({ children: [new TextRun("")], spacing: { before: 60, after: 60 } });
}

function centeredBold(text, size = 24) {
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { before: 120, after: 120 },
    children: [new TextRun({ text, bold: true, size, font: "Times New Roman" })]
  });
}

function centered(text) {
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { before: 80, after: 80 },
    children: [new TextRun({ text, size: 24, font: "Times New Roman" })]
  });
}

function lineBreak() {
  return new Paragraph({
    border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: "1F4E79", space: 1 } },
    spacing: { before: 160, after: 160 },
    children: [new TextRun("")]
  });
}

